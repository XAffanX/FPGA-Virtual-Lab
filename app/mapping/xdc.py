"""Read and write Xilinx Design Constraints (XDC) pin assignments.

Only PACKAGE_PIN constraints matter for the virtual board; everything else
(IOSTANDARD, create_clock, configuration properties ...) is accepted and ignored.
Pins are resolved through the board definition, which was generated from
Digilent's Basys-3-Master.xdc.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from app.board.board import Board
from app.compiler.compiler import Port

from .mapping import Issue, Mapping, make_key, parse_key

_GET_PORTS = re.compile(r"\[\s*get_ports\s+(\{[^}]*\}|\"[^\"]*\"|[^\]\s]+)\s*\]")
_PIN_DICT = re.compile(r"PACKAGE_PIN\s+([A-Za-z0-9]+)", re.I)
_PIN_PROP = re.compile(r"set_property\s+PACKAGE_PIN\s+([A-Za-z0-9]+)", re.I)


@dataclass
class XdcResult:
    mapping: Mapping
    pins: dict[str, str] = field(default_factory=dict)        # signal key -> package pin
    issues: list[Issue] = field(default_factory=list)


def _clean_port(text: str) -> list[str]:
    text = text.strip()
    if text[:1] in "{\"":
        text = text[1:-1]
    return [t for t in text.split() if t]


def parse_xdc_text(text: str, board: Board, ports: list[Port] | None = None) -> XdcResult:
    """Translate PACKAGE_PIN constraints into a signal -> board-resource mapping."""
    res = XdcResult(Mapping())
    port_by_name = {p.name: p for p in ports or []}
    # Join Tcl line continuations.
    text = re.sub(r"\\\r?\n", " ", text)
    for lineno, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip() if not raw.lstrip().startswith("#") else ""
        if not line or "PACKAGE_PIN" not in line.upper():
            continue
        pm = _PIN_PROP.search(line) or _PIN_DICT.search(line)
        gp = _GET_PORTS.search(line)
        if not pm or not gp:
            res.issues.append(Issue("warning", f"line {lineno}: could not understand constraint: {raw.strip()}"))
            continue
        pin = pm.group(1).upper()
        for name in _clean_port(gp.group(1)):
            try:
                pname, idx = parse_key(name)
            except ValueError:
                res.issues.append(Issue("warning", f"line {lineno}: unsupported port pattern '{name}'"))
                continue
            port = port_by_name.get(pname)
            if ports is not None and port is None:
                res.issues.append(Issue("warning", f"line {lineno}: '{name}' is constrained to {pin} but the "
                                        "top module has no such port (constraint ignored)", name))
                continue
            if port is not None and not port.is_vector:
                idx = None
            key = make_key(pname, idx)
            r = board.by_pin(pin)
            if r is None:
                what = board.unsupported_pins.get(pin)
                if what:
                    res.issues.append(Issue("warning", f"line {lineno}: '{key}' uses pin {pin} ({what}), which "
                                            "is not simulated in this version", key))
                else:
                    res.issues.append(Issue("error", f"line {lineno}: pin {pin} for '{key}' does not exist "
                                            f"on the {board.name} I/O map", key))
                continue
            if key in res.mapping.entries and res.mapping.entries[key] != r.id:
                res.issues.append(Issue("warning", f"line {lineno}: '{key}' constrained twice; using {pin}", key))
            res.mapping.entries[key] = r.id
            res.pins[key] = pin
    if not res.mapping.entries and not res.issues:
        res.issues.append(Issue("warning", "no PACKAGE_PIN constraints found"))
    return res


def parse_xdc(path: Path, board: Board, ports: list[Port] | None = None) -> XdcResult:
    return parse_xdc_text(Path(path).read_text(encoding="utf-8", errors="replace"), board, ports)


def export_xdc(mapping: Mapping, board: Board, ports: list[Port] | None = None) -> str:
    """Write a Vivado-compatible XDC for the mapping (Basys 3 master-XDC style)."""
    lines = [f"## {board.name} constraints generated by FPGA Virtual Lab",
             f"## Pins from Digilent's master XDC ({board.fpga})", ""]
    clock_keys = []
    for key, rid in mapping.to_dict().items():
        r = board.resources.get(rid)
        if r is None:
            continue
        name = key if "[" not in key else "{" + key + "}"
        lines.append(f"set_property -dict {{ PACKAGE_PIN {r.pin}   IOSTANDARD LVCMOS33 }} "
                     f"[get_ports {name}]; # {r.label}")
        if rid == board.clock_resource:
            clock_keys.append(name)
    for name in clock_keys:
        lines.append(f"create_clock -add -name sys_clk_pin -period {board.clock_period_ns:.2f} "
                     f"-waveform {{0 {board.clock_period_ns / 2:g}}} [get_ports {name}]")
    lines += ["", "set_property CONFIG_VOLTAGE 3.3 [current_design]",
              "set_property CFGBVS VCCO [current_design]", ""]
    return "\n".join(lines)
